const L = (x1, y1, x2, y2) => ({ pts: [[x1, y1], [x2, y2]] });
const P = (...pts) => ({ pts });
const C = (...pts) => ({ pts, curve: true });
const ring = (cx, cy, r, n = 8) => ({ pts: Array.from({ length: n }, (_, i) => [cx + r * Math.cos((2 * Math.PI * i) / n), cy + r * Math.sin((2 * Math.PI * i) / n)]), curve: true, closed: true });
const oval = (cx, cy, rx, ry, n = 8) => ({ pts: Array.from({ length: n }, (_, i) => [cx + rx * Math.cos((2 * Math.PI * i) / n), cy + ry * Math.sin((2 * Math.PI * i) / n)]), curve: true, closed: true });
const wave = (y, x0 = 0.15, x1 = 0.85, amp = 0.06, n = 3) => ({ pts: Array.from({ length: 2 * n + 1 }, (_, i) => [x0 + ((x1 - x0) * i) / (2 * n), y + (i % 2 ? -amp : amp)]), curve: true });
const box = (x0, y0, x1, y1) => ({ pts: [[x0, y0], [x1, y0], [x1, y1], [x0, y1]], closed: true });
