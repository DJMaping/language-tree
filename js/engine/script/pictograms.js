/**
 * The pictures writing began with.
 *
 * Every script Earth invented started as pictures of things: the Sumerian
 * signs for head, mouth, water, grain, ox and star; the Egyptian owl, water,
 * mouth, reed and hand; the Chinese sun, moon, mountain, tree, fire and
 * person. The signs here are drawn for the same things, in the simple way a
 * first scribe draws them, and an inventing language (invent.js) takes the
 * ones it has words for. From there everything is history: the knife
 * straightens them, the pen joins them, and a borrowing people reads them
 * by the first sound of its own word for the picture (adopt.js), which is
 * how the Phoenician ox became A and the water M.
 *
 * Each drawing is a few strokes in a unit box, y down. Nothing here is a
 * letter yet.
 */

