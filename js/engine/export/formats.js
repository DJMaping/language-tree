// PolyGlot
// ---------------------------------------------------------------------------

const xmlEscape = (s) => String(s ?? '')
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&apos;');

/**
 * PolyGlot's dictionary XML.
 *
 * A .pgd file is a ZIP whose main entry is PGDictionary.xml. The schema is
 * verbose but shallow: a properties block, a list of parts of speech, then one
 * <word> per entry.
 */
export function polyglotXml(state, opts = {}) {
    const name = opts.name || state.node?.name || state.langId;
    const POS = [...new Set(state.entries.filter((e) => !e.paradigm).map((e) => e.pos))].filter(Boolean);
    const posId = new Map(POS.map((p, i) => [p, i + 1]));

    const POS_NAMES = {
        n: 'noun', v: 'verb', adj: 'adjective', adv: 'adverb', pron: 'pronoun',
        dem: 'demonstrative', num: 'numeral', quant: 'quantifier',
        interrog: 'interrogative', neg: 'negator', adp: 'adposition',
        conj: 'conjunction', part: 'particle',
    };

    const L = [];
    L.push('<?xml version="1.0" encoding="UTF-8"?>');
    L.push('<dictionary>');
    L.push('<languageProperties>');
    L.push(`<langName>${xmlEscape(name)}</langName>`);
    L.push(`<localLangName>English</localLangName>`);
    L.push(`<langPropAuthorCopyright>${xmlEscape(
        `Generated by the Andah language tree. ${describeLanguage(state)}.`)}</langPropAuthorCopyright>`);
    L.push('<langPropTypeMandatory>F</langPropTypeMandatory>');
    L.push('<langPropLocalMandatory>F</langPropLocalMandatory>');
    L.push('<langPropWordUniqueness>F</langPropWordUniqueness>');
    L.push('<langPropLocalUniqueness>F</langPropLocalUniqueness>');
    L.push('<langPropIgnoreCase>F</langPropIgnoreCase>');
    L.push('</languageProperties>');

    for (const p of POS) {
        L.push('<partOfSpeech>');
        L.push(`<classId>${posId.get(p)}</classId>`);
        L.push(`<className>${xmlEscape(POS_NAMES[p] || p)}</className>`);
        L.push('<classNotes></classNotes>');
        L.push('</partOfSpeech>');
    }

    let id = 1;
    for (const e of state.entries.filter((x) => !x.paradigm && !x.retired).sort((a, b) => a.rank - b.rank)) {
        L.push('<word>');
        L.push(`<wordId>${id++}</wordId>`);
        L.push(`<localWord>${xmlEscape(e.gloss)}</localWord>`);
        L.push(`<conWord>${xmlEscape(state.romanisation.spell(e.form))}</conWord>`);
        L.push(`<wordTypeId>${posId.get(e.pos) ?? 0}</wordTypeId>`);
        L.push(`<pronunciation>${xmlEscape(e.ipa)}</pronunciation>`);
        const notes = [];
        if (e.loan) notes.push(`Loan from ${e.loan.from}, c.${e.loan.year} (${e.loan.kind}).`);
        if (e.replaced) notes.push(`Took over this meaning c.${e.replaced.year}; formerly "${e.formerGloss}".`);
        if (e.derivedFrom) notes.push(`Derived: ${e.derivedFrom.affix}.`);
        const h = state.histories?.get(e.id);
        if (h?.steps?.length) {
            notes.push(`From *${h.protoForm}: ${[...h.steps.filter((s) => s.applied).map((s) => s.to)].join(' > ')}`);
        }
        L.push(`<definition>${xmlEscape(notes.join(' '))}</definition>`);
        L.push('</word>');
    }

    L.push('</dictionary>');
    return L.join('\n');
}

// ---------------------------------------------------------------------------
// A minimal ZIP writer, so .pgd files come out openable
// ---------------------------------------------------------------------------

const CRC_TABLE = (() => {
    const t = new Uint32Array(256);
    for (let n = 0; n < 256; n++) {
        let c = n;
        for (let k = 0; k < 8; k++) c = (c & 1) ? (0xEDB88320 ^ (c >>> 1)) : (c >>> 1);
        t[n] = c >>> 0;
    }
    return t;
})();

function crc32(bytes) {
    let c = 0xFFFFFFFF;
    for (let i = 0; i < bytes.length; i++) c = CRC_TABLE[(c ^ bytes[i]) & 0xFF] ^ (c >>> 8);
    return (c ^ 0xFFFFFFFF) >>> 0;
}

/**
 * Write a ZIP with no compression (store method).
 *
 * Deliberately the simplest thing that works: a .pgd is a handful of kilobytes
 * of XML, and pulling in a deflate implementation to save a few of them would
 * cost the zero-dependency guarantee this whole engine is built on. Every ZIP
 * reader supports stored entries.
 */
export function zip(files) {
    const enc = new TextEncoder();
    const chunks = [];
    const central = [];
    let offset = 0;

    const u16 = (n) => [n & 0xFF, (n >>> 8) & 0xFF];
    const u32 = (n) => [n & 0xFF, (n >>> 8) & 0xFF, (n >>> 16) & 0xFF, (n >>> 24) & 0xFF];

    for (const [nameStr, contentStr] of Object.entries(files)) {
        const name = enc.encode(nameStr);
        const data = enc.encode(contentStr);
        const crc = crc32(data);

        const local = [
            ...u32(0x04034b50), ...u16(20), ...u16(0), ...u16(0),
            ...u16(0), ...u16(0),                       // time, date
            ...u32(crc), ...u32(data.length), ...u32(data.length),
            ...u16(name.length), ...u16(0),
        ];
        chunks.push(Uint8Array.from(local), name, data);

        central.push(Uint8Array.from([
            ...u32(0x02014b50), ...u16(20), ...u16(20), ...u16(0), ...u16(0),
            ...u16(0), ...u16(0),
            ...u32(crc), ...u32(data.length), ...u32(data.length),
            ...u16(name.length), ...u16(0), ...u16(0), ...u16(0), ...u16(0),
            ...u32(0), ...u32(offset),
        ]), name);

        offset += local.length + name.length + data.length;
    }

    const centralSize = central.reduce((n, c) => n + c.length, 0);
    const end = Uint8Array.from([
        ...u32(0x06054b50), ...u16(0), ...u16(0),
        ...u16(Object.keys(files).length), ...u16(Object.keys(files).length),
        ...u32(centralSize), ...u32(offset), ...u16(0),
    ]);

    const all = [...chunks, ...central, end];
    const total = all.reduce((n, c) => n + c.length, 0);
    const out = new Uint8Array(total);
    let p = 0;
    for (const c of all) { out.set(c, p); p += c.length; }
    return out;
}

/** A complete .pgd, ready to open. */
export function polyglotPgd(state, opts = {}) {
    return zip({ 'PGDictionary.xml': polyglotXml(state, opts) });
}

