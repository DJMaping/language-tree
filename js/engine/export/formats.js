/** The whole derived stage, JSON-safe. */
export function stageJson(state) {
    return JSON.stringify({
        language: state.node?.name ?? state.langId,
        born: state.node?.born, died: state.node?.died,
        description: describeLanguage(state),
        inventory: {
            consonants: state.inventory.consonants.map((c) => ({ ipa: c.ipa, ...c.f })),
            vowels: state.inventory.vowels.map((v) => ({ ipa: v.ipa, ...v.f })),
        },
        phonotactics: {
            syllable: state.phonotactics.syllable,
            coda: state.phonotactics.coda?.allowed,
            diphthongs: state.phonotactics.nucleus?.diphthongs,
            stress: state.phonotactics.stress?.rule,
        },
        romanisation: Object.fromEntries(state.romanisation.map),
        paradigm: state.paradigm ? {
            categories: state.paradigm.categories,
            classes: Object.fromEntries(Object.entries(state.paradigm.classes).map(([k, c]) => [k, {
                exemplar: c.exemplarGloss, members: c.members,
                cells: Object.fromEntries(Object.entries(c.cells || {}).map(([n, v]) => [n, v.ipa])),
            }])),
        } : null,
        erosion: state.erosion ? { survival: state.erosion.survival, cells: state.erosion.cells, distinct: state.erosion.distinct } : null,
        sentences: SENTENCES.map((s) => { try { const r = renderSentence(state, s); return { english: r.english, spelling: r.spelling, ipa: r.ipa }; } catch { return null; } }).filter(Boolean),
        lexicon: state.entries.filter((e) => !e.paradigm).map((e) => ({
            spelling: state.romanisation.spell(e.form), ipa: e.ipa, gloss: e.gloss,
            pos: e.pos, domain: e.domain, class: e.class, rank: e.rank,
            retired: e.retired || undefined, loan: e.loan || undefined,
        })),
    }, null, 1);
}
