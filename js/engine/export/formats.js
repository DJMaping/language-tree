/**
 * Exports: getting a generated language out of this tool and into the ones DJ
 * already uses.
 *
 * A language that exists only inside its own generator is a demo. These four
 * formats are the ones that make it a working artefact:
 *
 *   CSV       a dictionary anything can read, including PolyGlot's importer
 *   PolyGlot  a .pgd the conlanging tool opens directly
 *   Markdown  a grammar sketch to read, print, or paste into the wiki
 *   JSON      the whole derived stage, for anything else
 *
 * Everything here is pure string-building, no filesystem — the caller decides
 * where bytes go, so the same code serves the CLI and a browser download.
 */

