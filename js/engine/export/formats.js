/**
 * A readable grammar sketch in Markdown.
 *
 * Structured the way a reference grammar is: what it sounds like, what the
 * phonemes are, how syllables are built, how words inflect, what changed to get
 * here, and a text. That ordering is not arbitrary — it is the order in which
 * each section depends on the one before it.
 */
export function grammarSketch(state, opts = {}) {
    const name = opts.name || state.node?.name || state.langId;
    const inv = state.inventory;
    const pt = state.phonotactics;
    const M = [];

    M.push(`# ${name}`);
    if (state.node) {
        M.push(`*${state.node.born}${state.node.died != null ? `–${state.node.died}` : '–present'}*`);
    }
    M.push('');
    M.push(describeLanguage(state) + '.');
    M.push('');

    if (opts.lineage?.length) {
        M.push(`**Descent:** ${opts.lineage.join(' → ')}`);
        M.push('');
    }

    // ── Sample text ────────────────────────────────────────────────────────
    M.push('## Sample text');
    M.push('');
    for (const s of SENTENCES) {
        let r = null;
        try { r = renderSentence(state, s); } catch { continue; }
        if (!r) continue;
        M.push(`> **${r.spelling}**  `);
        M.push(`> /${r.ipa}/  `);
        M.push(`> ‘${r.english}’`);
        M.push('');
        if (r.long && r.readerIpa) {
            M.push('For an online IPA reader (tie bars and tone letters removed, since');
            M.push('Amazon Polly cannot voice them — you hear the segments and the rhythm,');
            M.push('not the tone):');
            M.push('');
            M.push('```');
            M.push(r.readerIpa);
            M.push('```');
            M.push('');
        }
    }

    // ── Phonology ──────────────────────────────────────────────────────────
    M.push('## Phonology');
    M.push('');
    const PLACE = ['bilabial', 'labiodental', 'dental', 'alveolar', 'postalveolar', 'retroflex', 'alveolopalatal', 'palatal', 'velar', 'labiovelar', 'uvular', 'pharyngeal', 'glottal'];
    const MANNER = ['stop', 'affricate', 'fricative', 'nasal', 'trill', 'tap', 'approximant'];
    const places = PLACE.filter((p) => inv.consonants.some((c) => c.f.place === p));
    M.push(`| | ${places.map((p) => p.slice(0, 8)).join(' | ')} |`);
    M.push(`|---|${places.map(() => '---').join('|')}|`);
    for (const m of [...MANNER, 'lateral']) {
        const row = m === 'lateral'
            ? inv.consonants.filter((c) => c.f.lateral)
            : inv.consonants.filter((c) => c.f.manner === m && !c.f.lateral);
        if (!row.length) continue;
        M.push(`| **${m}** | ${places.map((p) => row.filter((c) => c.f.place === p).map((c) => c.ipa).join(' ')).join(' | ')} |`);
    }
    M.push('');
    const qualities = [...new Set(inv.vowels.map((v) => v.ipa.replace(/[ː˩˨˧˦˥̃]/gu, '')))];
    M.push(`**Vowels:** ${qualities.join(' ')}`);
    if (inv.vowels.some((v) => v.f.tone)) {
        M.push('');
        M.push(`**Tone:** contrastive, ${new Set(inv.vowels.map((v) => v.f.tone).filter(Boolean)).size} level(s).`);
    }
    M.push('');
    M.push('### Phonotactics');
    M.push('');
    M.push(`- Syllable: \`${pt.syllable || '(C)V(C)'}\``);
    M.push(`- Coda: ${pt.coda?.max === 0 ? 'none — all syllables open' : (pt.coda?.allowed || []).join(' ') || 'unrestricted'}`);
    if (pt.nucleus?.diphthongs?.length) M.push(`- Diphthongs: ${pt.nucleus.diphthongs.join(' ')}`);
    M.push(`- Stress: ${pt.stress?.label || pt.stress?.rule}`);
    if (pt.stress?.note) M.push(`  - ${pt.stress.note}`);
    M.push('');
    M.push(`**Romanisation:** ${[...inv.consonants, ...inv.vowels]
        .map((ph) => [ph.ipa, state.romanisation.map.get(ph.ipa)])
        .filter(([i, l]) => l && l !== i).map(([i, l]) => `${i}=${l}`).join(', ') || 'one-to-one with the IPA'}`);
    M.push('');

    // ── Grammar ────────────────────────────────────────────────────────────
    if (state.paradigm?.classes && Object.keys(state.paradigm.classes).length) {
        M.push('## Grammar');
        M.push('');
        const cats = state.paradigm.categories || {};
        M.push(`**Type:** ${cats.type}. ${cats.typeNote || ''}`);
        M.push('');
        if (cats.cases?.length) M.push(`**Cases:** ${cats.cases.join(', ')}. **Numbers:** ${(cats.numbers || []).join(', ')}.`);
        M.push('');
        if (state.erosion?.survival != null) {
            M.push(`**Inflection retained:** ${Math.round(state.erosion.survival * 100)}% — ${state.erosion.distinct} of ${state.erosion.cells} cells still distinct across ${state.erosion.classes} classes.`);
            M.push('');
        }
        for (const cls of Object.keys(state.paradigm.classes).sort().slice(0, 4)) {
            M.push('```');
            M.push(formatParadigm(state.paradigm, cls));
            M.push('```');
            M.push('');
        }
        if (state.erosion?.mergers?.length) {
            M.push('### Syncretism');
            M.push('');
            for (const m of state.erosion.mergers.slice(0, 10)) {
                M.push(`- **${m.cls}** ${m.cells.join(' = ')} /${m.ipa}/${m.cause === 'sound-change' ? ` — merged by ${m.label}${m.year != null ? `, c. ${m.year}` : ''}` : ''}`);
            }
            M.push('');
        }
    }

    // ── History ────────────────────────────────────────────────────────────
    if (state.changeSet) {
        M.push('## Sound changes on this edge');
        M.push('');
        M.push(`${state.changeSet.from} → ${state.changeSet.to}, about one change per ${state.changeSet.interval} years.`);
        M.push('');
        for (const r of state.changeSet.rules) {
            M.push(`- **c. ${r.year}** — ${r.label}${r.analogue ? `  \n  *cf. ${r.analogue}*` : ''}`);
        }
        M.push('');
        if (state.changeSet.replacements?.length) {
            M.push('### Vocabulary replaced');
            M.push('');
            for (const ev of state.changeSet.replacements.slice(0, 12)) {
                M.push(`- **c. ${ev.year}** — “${ev.meaning}” changed word (${ev.strategy})`);
            }
            M.push('');
        }
    }

    // ── Loanwords ──────────────────────────────────────────────────────────
    const loans = state.entries.filter((e) => e.loan);
    if (loans.length) {
        M.push('## Loanwords');
        M.push('');
        for (const l of loans.slice(0, 20)) {
            M.push(`- **${state.romanisation.spell(l.form)}** /${l.ipa}/ ‘${l.gloss}’ — from ${l.loan.from}, c. ${l.loan.year} (${l.loan.kind})`);
        }
        M.push('');
    }

    // ── Lexicon ────────────────────────────────────────────────────────────
    M.push('## Core lexicon');
    M.push('');
    M.push('| word | IPA | meaning | origin |');
    M.push('|---|---|---|---|');
    for (const e of state.entries.filter((x) => x.core && !x.retired && !x.paradigm).sort((a, b) => a.rank - b.rank).slice(0, opts.lexiconLimit ?? 120)) {
        const origin = e.loan ? 'loan' : e.replaced ? `< “${e.formerGloss}”` : e.derivedFrom ? 'derived' : 'inherited';
        M.push(`| ${state.romanisation.spell(e.form)} | /${e.ipa}/ | ${e.gloss} | ${origin} |`);
    }
    M.push('');
    return M.join('\n');
}

