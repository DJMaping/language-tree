import { formatParadigm } from '../morphology/paradigm.js';
import { formatErosion } from '../morphology/erosion.js';
import { SENTENCES, renderSentence, describeLanguage } from '../text/sentence.js';

// ---------------------------------------------------------------------------
// CSV
// ---------------------------------------------------------------------------

const csvCell = (v) => {
    const s = v == null ? '' : String(v);
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

/**
 * The lexicon as CSV, with the etymology chain flattened into a column.
 *
 * Column order matters: PolyGlot's importer maps columns by position, and
 * word / pronunciation / definition / part-of-speech is the order it expects.
 */
export function lexiconCsv(state, opts = {}) {
    const rows = [[
        'word', 'ipa', 'gloss', 'pos', 'domain', 'class', 'rank',
        'syllables', 'origin', 'etymology',
    ]];

    const entries = state.entries
        .filter((e) => !e.paradigm)
        .filter((e) => (opts.includeArchaic ? true : !e.retired))
        .sort((a, b) => a.rank - b.rank);

    for (const e of entries) {
        const history = state.histories?.get(e.id);
        const chain = history
            ? [`*${history.protoForm}`, ...history.steps.filter((s) => s.applied).map((s) => s.to)].join(' > ')
            : '';
        const origin = e.loan ? `loan (${e.loan.kind}, c.${e.loan.year})`
            : e.replaced ? `replaced "${e.formerGloss}" (${e.replaced.strategy})`
                : e.retired ? `archaic, displaced`
                    : e.derivedFrom ? `derived (${e.derivedFrom.affix})`
                        : 'inherited';
        rows.push([
            state.romanisation.spell(e.form), e.ipa, e.gloss, e.pos, e.domain,
            e.class ?? '', e.rank, e.syllables ?? '', origin, chain,
        ]);
    }
    return rows.map((r) => r.map(csvCell).join(',')).join('\n');
}

